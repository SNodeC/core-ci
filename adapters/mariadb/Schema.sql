CREATE TABLE IF NOT EXISTS coreci_schema (
    version INT UNSIGNED NOT NULL PRIMARY KEY
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS coreci_records (
    section VARCHAR(32) NOT NULL,
    record_key VARCHAR(512) NOT NULL,
    payload LONGTEXT NOT NULL CHECK (JSON_VALID(payload)),
    PRIMARY KEY (section, record_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS coreci_log (
    sequence BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    logged_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    description TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
